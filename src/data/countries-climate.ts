// Helpers pour obtenir les différents classements
export function getTopEmitters(limit = 10): CountryClimateData[] {
  return [...countriesClimateData]
    .sort((a, b) => b.co2Emissions2024 - a.co2Emissions2024)
    .slice(0, limit);
}

export function getTopEmittersPerCapita(limit = 10): CountryClimateData[] {
  return [...countriesClimateData]
    .sort((a, b) => b.co2EmissionsPerCapita - a.co2EmissionsPerCapita)
    .slice(0, limit);
}

export function getMostVulnerableCountries(limit = 10): CountryClimateData[] {
  return [...countriesClimateData]
    .sort((a, b) => b.climateRiskIndex - a.climateRiskIndex)
    .slice(0, limit);
}

export function getClimateLeaders(limit = 10): CountryClimateData[] {
  return [...countriesClimateData]
    .sort((a, b) => b.climateActionScore - a.climateActionScore)
    .slice(0, limit);
}

export function getRenewableLeaders(limit = 10): CountryClimateData[] {
  return [...countriesClimateData]
    .sort((a, b) => b.renewableShare - a.renewableShare)
    .slice(0, limit);
}

export function getCountriesWithNetZero(): CountryClimateData[] {
  return countriesClimateData
    .filter((c) => c.netZeroTarget !== null)
    .sort((a, b) => (a.netZeroTarget ?? 2100) - (b.netZeroTarget ?? 2100));
}

export function getParisAlignedCountries(): CountryClimateData[] {
  return countriesClimateData.filter((c) => c.parisAligned);
}

// Fonction pour exporter en CSV
export function exportToCSV(data: CountryClimateData[]): string {
  const headers = [
    "Rang",
    "Pays",
    "Code",
    "Émissions CO2 (Mt)",
    "Émissions/habitant (t)",
    "Part mondiale (%)",
    "Tendance émissions (%)",
    "Indice risque climatique",
    "Score vulnérabilité",
    "Score préparation",
    "Score action climatique",
    "Part renouvelable (%)",
    "Croissance renouvelable (%)",
    "Objectif neutralité",
    "Aligné Paris",
  ];

  const rows = data.map((c) => [
    c.rank,
    c.country,
    c.countryCode,
    c.co2Emissions2024,
    c.co2EmissionsPerCapita,
    c.shareGlobalEmissions,
    c.emissionsTrend,
    c.climateRiskIndex,
    c.vulnerabilityScore,
    c.readinessScore,
    c.climateActionScore,
    c.renewableShare,
    c.renewableGrowth,
    c.netZeroTarget ?? "N/A",
    c.parisAligned ? "Oui" : "Non",
  ]);

  return [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
}
